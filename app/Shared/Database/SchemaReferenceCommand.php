<?php

declare(strict_types=1);

namespace App\Shared\Database;

use Illuminate\Console\Command;
use Illuminate\Database\Connection;
use Illuminate\Database\DatabaseManager;
use Illuminate\Filesystem\Filesystem;
use Illuminate\Support\Facades\Artisan;
use RuntimeException;

/**
 * Writes the field reference: every table and column of the central database and of a store database, with the comments migrations give them (CLAUDE.md section 12).
 *
 * The central side is read from the central database. The store side is read
 * from a throwaway database migrated with the store migrations for the
 * purpose and dropped afterwards, so it shows exactly what the migrations on
 * disk make, never a particular store. The files go to the git-ignored
 * api-docs/ folder by default, next to the OpenAPI exports.
 */
final class SchemaReferenceCommand extends Command
{
    protected $signature = 'schema:reference
        {--path=api-docs : Folder to write fields-central.md and fields-store.md into, relative to the project}';

    protected $description = 'Write the field reference of the central and store databases from their comments';

    private const string THROWAWAY_CONNECTION = 'schema_reference';

    public function handle(DatabaseManager $databases, TableDescriptions $tableDescriptions, Filesystem $files): int
    {
        $folder = base_path($this->stringOption('path'));
        $files->ensureDirectoryExists($folder);

        $central = $databases->connection(config()->string('tenancy.database.central_connection'));
        $files->put($folder.'/fields-central.md', $this->markdown('central database', $tableDescriptions->of($central)));

        $store = $this->inThrowawayStoreDatabase($databases, $central, static fn (Connection $connection): array => $tableDescriptions->of($connection));
        $files->put($folder.'/fields-store.md', $this->markdown('store database', $store));

        $this->components->info('Wrote fields-central.md ('.count($tableDescriptions->of($central)).' tables) and fields-store.md ('.count($store).' tables) to '.$this->stringOption('path').'.');

        return self::SUCCESS;
    }

    /**
     * Creates an empty database next to the central one, runs the store migrations on it, reads it, and drops it whatever happens.
     *
     * @template TResult
     *
     * @param  callable(Connection): TResult  $read
     * @return TResult
     */
    private function inThrowawayStoreDatabase(DatabaseManager $databases, Connection $central, callable $read): mixed
    {
        // Made from a fixed prefix and random hex only, so it is safe to put in the statement.
        $name = 'schema_reference_'.bin2hex(random_bytes(6));
        $central->statement('create database "'.$name.'"');

        try {
            config(['database.connections.'.self::THROWAWAY_CONNECTION => [...config()->array('database.connections.'.$central->getName()), 'database' => $name]]);
            $databases->purge(self::THROWAWAY_CONNECTION);

            $exitCode = Artisan::call('migrate', [
                '--database' => self::THROWAWAY_CONNECTION,
                '--path' => database_path('migrations/tenant'),
                '--realpath' => true,
                '--force' => true,
            ]);

            if ($exitCode !== self::SUCCESS) {
                throw new RuntimeException('The store migrations failed on the throwaway database: '.Artisan::output());
            }

            return $read($databases->connection(self::THROWAWAY_CONNECTION));
        } finally {
            $databases->purge(self::THROWAWAY_CONNECTION);
            $central->statement('drop database if exists "'.$name.'" with (force)');
        }
    }

    /**
     * @param  array<string, array{comment: string|null, columns: array<string, array{type: string, nullable: bool, comment: string|null}>}>  $tables
     */
    private function markdown(string $title, array $tables): string
    {
        $lines = [
            "# Field reference: {$title}",
            '',
            'Generated by `php artisan schema:reference` from the comments the migrations give each table and column. Don\'t edit it; change the comments in a migration instead.',
        ];

        foreach ($tables as $table => $description) {
            $lines[] = '';
            $lines[] = "## {$table}";
            $lines[] = '';
            $lines[] = $description['comment'] ?? '_No description._';
            $lines[] = '';
            $lines[] = '| Column | Type | Null | Description |';
            $lines[] = '| --- | --- | --- | --- |';

            foreach ($description['columns'] as $column => $details) {
                $lines[] = sprintf('| `%s` | %s | %s | %s |', $column, $details['type'], $details['nullable'] ? 'yes' : 'no', $this->cell($details['comment'] ?? ''));
            }
        }

        return implode("\n", $lines)."\n";
    }

    private function cell(string $text): string
    {
        return str_replace(['|', "\n"], ['\|', ' '], $text);
    }

    private function stringOption(string $name): string
    {
        $value = $this->option($name);

        return is_string($value) && $value !== '' ? $value : 'api-docs';
    }
}
